document.addEventListener("DOMContentLoaded", () => {
  const modal = document.getElementById("cert-modal");
  const pdfContainer = document.getElementById("cert-pdf-container");
  const closeBtn = document.querySelector(".close-btn");
  const themeToggle = document.getElementById("theme-toggle");
  const languageToggle = document.getElementById("language-toggle");
  let currentLanguage = "en";

  const getStoredPreference = key => {
    try {
      return localStorage.getItem(key);
    } catch (error) {
      return null;
    }
  };

  const setStoredPreference = (key, value) => {
    try {
      localStorage.setItem(key, value);
    } catch (error) {
      // The current session remains usable when storage is unavailable.
    }
  };

  const setTheme = isDark => {
    document.body.classList.toggle("dark", isDark);
    if (themeToggle) {
      themeToggle.innerHTML = isDark
        ? '<svg viewBox="0 0 24 24" aria-hidden="true" focusable="false"><circle cx="12" cy="12" r="4"></circle><path d="M12 2v2m0 16v2M4.93 4.93l1.42 1.42m11.3 11.3 1.42 1.42M2 12h2m16 0h2M4.93 19.07l1.42-1.42m11.3-11.3 1.42-1.42"></path></svg>'
        : '<svg viewBox="0 0 24 24" aria-hidden="true" focusable="false"><path d="M20.9 13A9 9 0 0 1 11 3.1 9 9 0 1 0 20.9 13Z"></path></svg>';
      const themeLabel = isDark ? "Switch to light theme" : "Switch to dark theme";
      themeToggle.setAttribute(
        "aria-label",
        currentLanguage === "ar"
          ? isDark ? "التبديل إلى المظهر الفاتح" : "التبديل إلى المظهر الداكن"
          : themeLabel
      );
      themeToggle.setAttribute("aria-pressed", String(isDark));
    }
    setStoredPreference("theme", isDark ? "dark" : "light");
  };

  const setLanguage = language => {
    currentLanguage = language === "ar" ? "ar" : "en";
    const isArabic = currentLanguage === "ar";
    document.documentElement.lang = currentLanguage;
    document.documentElement.dir = isArabic ? "rtl" : "ltr";
    document.body.classList.toggle("arabic", isArabic);

    document.querySelectorAll("[data-i18n]").forEach(element => {
      if (!element.dataset.i18nEnglish) {
        element.dataset.i18nEnglish = element.textContent;
      }
      element.textContent = isArabic
        ? arabicTranslations[element.dataset.i18n] || element.dataset.i18nEnglish
        : element.dataset.i18nEnglish;
    });

    document.querySelectorAll("[data-i18n-aria-label]").forEach(element => {
      if (!element.dataset.i18nEnglishAriaLabel) {
        element.dataset.i18nEnglishAriaLabel = element.getAttribute("aria-label") || "";
      }
      element.setAttribute(
        "aria-label",
        isArabic
          ? arabicTranslations[element.dataset.i18nAriaLabel] || element.dataset.i18nEnglishAriaLabel
          : element.dataset.i18nEnglishAriaLabel
      );
    });

    if (languageToggle) {
      languageToggle.textContent = isArabic ? "English" : "العربية";
      languageToggle.setAttribute("aria-label", isArabic ? "Switch language to English" : "التبديل إلى اللغة العربية");
    }

    setTheme(document.body.classList.contains("dark"));
    setStoredPreference("language", currentLanguage);
  };

  const closeModal = () => {
    if (!modal) return;
    modal.classList.remove("open");
    modal.setAttribute("aria-hidden", "true");
    document.body.classList.remove("modal-open");
  };

  if (languageToggle) {
    languageToggle.addEventListener("click", () => {
      setLanguage(currentLanguage === "en" ? "ar" : "en");
    });
  }

  // Modal functionality for certifications
  if (modal && pdfContainer) {
    document.querySelectorAll(".cert-link").forEach(link => {
      link.addEventListener("click", e => {
        e.preventDefault();
        const pdfs = link.dataset.certPdfs?.split(",") || [];
        pdfContainer.innerHTML = pdfs
          .map(pdf => `<iframe src="${pdf.trim()}" title="Certificate PDF"></iframe>`)
          .join("");
        modal.classList.add("open");
        modal.setAttribute("aria-hidden", "false");
        document.body.classList.add("modal-open");
      });
    });

    if (closeBtn) {
      closeBtn.addEventListener("click", closeModal);
    }

    // Close modal when clicking outside content
    modal.addEventListener("click", e => {
      if (e.target === modal) {
        closeModal();
      }
    });

    document.addEventListener("keydown", e => {
      if (e.key === "Escape" && modal.classList.contains("open")) {
        closeModal();
      }
    });
  }

  // Dark/Light Mode Toggle
  if (themeToggle) {
    const savedTheme = getStoredPreference("theme");
    const prefersDark = window.matchMedia("(prefers-color-scheme: dark)").matches;
    const initialDark = savedTheme ? savedTheme === "dark" : prefersDark;
    setTheme(initialDark);

    themeToggle.addEventListener("click", () => {
      setTheme(!document.body.classList.contains("dark"));
    });
  }

  setLanguage(getStoredPreference("language") || "en");
});
